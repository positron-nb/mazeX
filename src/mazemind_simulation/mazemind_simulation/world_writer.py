"""Write a Gazebo (Ignition Fortress, SDF 1.8) world for a generated maze."""

from __future__ import annotations

import math
from typing import List
from xml.sax.saxutils import escape

from mazemind_simulation.maze import Maze

WORLD_NAME = 'mazemind_world'

WALL_RGBA = '0.72 0.72 0.75 1'
FLOOR_RGBA = '0.35 0.35 0.38 1'
# The exit door is the only saturated green surface in the world; the camera
# detector keys on this hue. Emissive so it reads the same in any lighting.
DOOR_RGBA = '0.05 0.85 0.10 1'


def _box(name: str, x: float, y: float, z: float, yaw: float,
         sx: float, sy: float, sz: float, rgba: str, emissive: str = '0 0 0 1') -> str:
    return f"""
      <collision name="{name}_collision">
        <pose>{x:.4f} {y:.4f} {z:.4f} 0 0 {yaw:.6f}</pose>
        <geometry><box><size>{sx:.4f} {sy:.4f} {sz:.4f}</size></box></geometry>
      </collision>
      <visual name="{name}_visual">
        <pose>{x:.4f} {y:.4f} {z:.4f} 0 0 {yaw:.6f}</pose>
        <geometry><box><size>{sx:.4f} {sy:.4f} {sz:.4f}</size></box></geometry>
        <material>
          <ambient>{rgba}</ambient><diffuse>{rgba}</diffuse>
          <specular>0.1 0.1 0.1 1</specular><emissive>{emissive}</emissive>
        </material>
      </visual>"""


def overhead_camera_sdf(maze: Maze, image_size: int = 640, margin: float = 0.4) -> str:
    """Static top-down camera for demo recordings (published under /ground_truth/).

    Oriented so image-up = world +y and image-right = world +x. Gazebo only
    renders it while something subscribes, i.e. when recording is enabled.
    """
    cx, cy = maze.width / 2, maze.height / 2
    half = max(maze.width, maze.height) / 2 + margin
    height = 2.0 * half + 1.0
    hfov = 2.0 * math.atan(half / (height - 0.5))
    return f"""
    <model name="overhead_camera">
      <static>true</static>
      <pose>{cx:.3f} {cy:.3f} {height:.3f} 0 1.5707963 1.5707963</pose>
      <link name="link">
        <sensor name="overhead" type="camera">
          <topic>/ground_truth/overhead_camera</topic>
          <update_rate>5</update_rate>
          <always_on>true</always_on>
          <camera>
            <horizontal_fov>{hfov:.4f}</horizontal_fov>
            <image><width>{image_size}</width><height>{image_size}</height><format>R8G8B8</format></image>
            <clip><near>0.1</near><far>{height + 2:.1f}</far></clip>
          </camera>
        </sensor>
      </link>
    </model>"""


def world_sdf(maze: Maze, physics_step: float = 0.002, real_time_factor: float = 1.0) -> str:
    cfg = maze.config
    h = cfg.wall_height
    walls: List[str] = []
    for i, b in enumerate(maze.wall_boxes()):
        walls.append(_box(f'wall_{i}', b.cx, b.cy, h / 2, 0.0, b.sx, b.sy, h, WALL_RGBA))

    d = maze.door_pose()
    # Box local x is the door's width axis; rotate so the face normal = yaw.
    door = _box('door', d['x'], d['y'], d['z'], d['yaw'] + 1.5707963267948966,
                d['width'], d['thickness'], d['height'], DOOR_RGBA, emissive=DOOR_RGBA)

    floor_x, floor_y = maze.width / 2, maze.height / 2
    floor_sx, floor_sy = maze.width + 4.0, maze.height + 4.0
    title = escape(f'MazeMind {cfg.rows}x{cfg.cols} seed={cfg.seed}')

    return f"""<?xml version="1.0"?>
<!-- Generated by mazemind_simulation: {title}. Do not edit by hand. -->
<sdf version="1.8">
  <world name="{WORLD_NAME}">
    <physics name="default_physics" type="ode">
      <max_step_size>{physics_step}</max_step_size>
      <real_time_factor>{real_time_factor}</real_time_factor>
    </physics>
    <plugin filename="ignition-gazebo-physics-system" name="ignition::gazebo::systems::Physics"/>
    <plugin filename="ignition-gazebo-user-commands-system" name="ignition::gazebo::systems::UserCommands"/>
    <plugin filename="ignition-gazebo-scene-broadcaster-system"
            name="ignition::gazebo::systems::SceneBroadcaster"/>
    <plugin filename="ignition-gazebo-sensors-system" name="ignition::gazebo::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>
    <plugin filename="ignition-gazebo-contact-system" name="ignition::gazebo::systems::Contact"/>

    <scene>
      <ambient>0.6 0.6 0.6 1</ambient>
      <background>0.75 0.8 0.85 1</background>
      <shadows>false</shadows>
    </scene>

    <light type="directional" name="sun">
      <cast_shadows>false</cast_shadows>
      <pose>0 0 10 0 0 0</pose>
      <diffuse>0.9 0.9 0.9 1</diffuse>
      <specular>0.2 0.2 0.2 1</specular>
      <direction>-0.4 0.3 -0.85</direction>
    </light>

    <model name="ground_plane">
      <static>true</static>
      <link name="link">
        <collision name="collision">
          <geometry>
            <plane><normal>0 0 1</normal><size>{floor_sx:.2f} {floor_sy:.2f}</size></plane>
          </geometry>
        </collision>
        <visual name="visual">
          <pose>{floor_x:.3f} {floor_y:.3f} 0 0 0 0</pose>
          <geometry><plane><normal>0 0 1</normal><size>{floor_sx:.2f} {floor_sy:.2f}</size></plane></geometry>
          <material><ambient>{FLOOR_RGBA}</ambient><diffuse>{FLOOR_RGBA}</diffuse></material>
        </visual>
      </link>
    </model>

    <model name="maze">
      <static>true</static>
      <link name="walls">{''.join(walls)}
      </link>
    </model>

    <model name="exit_door">
      <static>true</static>
      <link name="panel">{door}
      </link>
    </model>
{overhead_camera_sdf(maze)}
  </world>
</sdf>
"""


def write_world(maze: Maze, path: str, **kwargs) -> None:
    with open(path, 'w', encoding='utf-8') as fh:
        fh.write(world_sdf(maze, **kwargs))
